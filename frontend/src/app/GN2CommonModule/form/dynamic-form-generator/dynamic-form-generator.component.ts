import { Component, OnInit, OnChanges, Input, Output, EventEmitter } from '@angular/core';
import { UntypedFormGroup, UntypedFormControl } from '@angular/forms';
import { DynamicFormService } from './dynamic-form.service';
import * as equal from 'fast-deep-equal/es6';
import { filter } from 'rxjs/operators';

/**
 * Ce composant permet de créer dynamiquement des formulaire à partir
 * de paramètres passés sous forme d'un tableau d'objets.
 */
@Component({
  selector: 'pnx-dynamic-form-generator',
  templateUrl: './dynamic-form-generator.component.html',
  styleUrls: ['./dynamic-form-generator.component.scss'],
})
export class GenericFormGeneratorComponent implements OnInit, OnChanges {
  /**
   * Passe à `true` une fois les contrôles générés par `initDynamicForm`. Permet au template
   * de n'afficher les champs qu'une fois le `myFormGroup` prêt.
   */
  public formControlBuilded = false;

  /**
   * Contrôle du champ select permettant de choisir le champ à ajouter au formulaire
   * (mode non auto-généré, `autoGenerated == false`). Sa valeur est la définition du champ choisi.
   */
  public selectControl = new UntypedFormControl();

  /**
   * Définitions des champs de `formsSelected` actuellement masqués
   * (propriété `hidden` évaluée avec la valeur courante du formulaire).
   */
  public formsHidden = [];

  /**
   * Définitions des champs de `formsSelected` actuellement affichés
   * (propriété `hidden` évaluée avec la valeur courante du formulaire).
   */
  public formsDisplayed = [];

  /**
   * Dernière valeur du formulaire émise par `change`. Sert à détecter un changement réel
   * de valeur (voir `hasValueChanged`).
   */
  public oldValue = {};

  /**
   * Drapeau transmis aux champs enfants pour leur signaler un changement de valeur du formulaire.
   * Passe à `true` après un changement puis revient à `false` 500 ms plus tard.
   */
  public update;

  /**
   * Groupe de formulaire auquel sont ajoutés les contrôles générés. S'il n'est pas fourni
   * en mode `autoGenerated`, il est créé par le composant.
   */
  @Input() myFormGroup: UntypedFormGroup;

  /**
   * Émet le `myFormGroup` à la fin de chaque génération des contrôles (permet le two-way binding
   * `[(myFormGroup)]`).
   */
  @Output() myFormGroupChange = new EventEmitter<any>();

  /**
   * Définitions des champs du formulaire. Chaque élément décrit un champ
   * (`attribut_name`, `attribut_label`, `type_widget`, `required`, `disabled`, `hidden`, ...).
   * Les définitions sans `type_widget` ne génèrent pas de contrôle.
   * En mode non auto-généré, ne contient que les champs encore sélectionnables.
   */
  @Input() formsDefinition: Array<any>;

  /**
   * Libellé du champ select de sélection des champs à ajouter
   * (mode non auto-généré, `autoGenerated == false`).
   */
  @Input() selectLabel: string;

  /**
   * Émet la nouvelle valeur du formulaire à chaque changement réel de valeur.
   */
  @Output() change = new EventEmitter<any>();

  /**
   * Est-ce que
   * - (autoGenerated == true) : tous les champs du formulaire sont présents
   * - (autoGenerated == false) : ou bien le formulaire doit être controlé par un champ select
   *   pour afficher/masquer les champs du formulaire.
   * Par défault (autoGenerated == false) le formulaire est controlé par un champ select.
   */
  @Input() autoGenerated = false;

  /**
   * Dictionnaire qui permet
   * - de donner des valeurs par défaut au formulaire
   * - et d'afficher les champs concernés
   *   (dans le cas où l'input autoGenerated est égal à false)
   * Exemple:
   *   defaults = {
   *     id_nomenclature_observation_status: [84],
   *     id_nomenclature_valid_status = [458,315,320,316,319,317]
   *   }
   */
  @Input() defaults: any;

  /**
   * Comportement lors d'un changement de `formsDefinition` (hors premier affichage).
   *
   * - `true` : seuls les contrôles créés par ce composant sont modifiés
   *   - ceux qui ne sont plus définis sont supprimés,
   *   - ceux qui sont toujours définis sont conservés (valeur incluse), seuls leurs validateurs
   *     et leur état activé/désactivé sont mis à jour,
   *   - les nouveaux sont ajoutés.
   *
   *   Les contrôles du `myFormGroup` qui n'ont pas été créés par ce composant (ex: un champ
   *   `geometry` ajouté par le formulaire parent) ne sont jamais touchés.
   * - `false` (par défaut) : tous les contrôles du `myFormGroup` sont supprimés puis recréés.
   *
   * @default false
   *
   */
  @Input() preserveControls = false;

  /**
   * Définitions des champs présents dans le formulaire. En mode `autoGenerated`, il s'agit
   * de toutes les `formsDefinition` ; sinon uniquement des champs ajoutés par l'utilisateur
   * (ou via `defaults`).
   */
  public formsSelected = [];

  /**
   * Noms des contrôles ajoutés au `myFormGroup` par ce composant. Permet de ne pas toucher aux
   * contrôles du formulaire parent lorsque `preserveControls` est activé.
   */
  private ownedControls = new Set<string>();

  constructor(private _dynformService: DynamicFormService) {}

  ngOnInit() {
    this.formsDefinition = this.formsDefinition || [];
    this.initDynamicForm();
    this.myFormGroup.valueChanges.subscribe((values) => {
      this.onFormsChange(values);
    });
  }

  /**
   * Régénère les contrôles lorsque `formsDefinition` change (sauf au premier changement, géré
   * par `ngOnInit`).
   *
   * Avec `preserveControls`, seuls les contrôles obsolètes créés par ce composant sont supprimés ;
   * sinon tous les contrôles du `myFormGroup` sont supprimés. Les contrôles sont ensuite
   * (re)générés par `initDynamicForm`.
   *
   * @param changes Changements des inputs du composant (SimpleChanges)
   */
  ngOnChanges(changes) {
    // on formdef changes, regenerate the form and UI
    // Do not load the form at first change: done by ngOnInit which wait for the component to be ready
    if (
      changes.formsDefinition &&
      !changes.formsDefinition.firstChange &&
      changes.formsDefinition.currentValue
    ) {
      if (this.preserveControls) {
        this.removeObsoleteControls();
      } else {
        for (const controlName in this.myFormGroup.controls) {
          this.myFormGroup.removeControl(controlName);
        }
        this.ownedControls.clear();
      }
      this.initDynamicForm();
    }
  }

  /**
   * Supprime du `myFormGroup` les contrôles créés par ce composant qui ne sont plus présents
   * dans `formsDefinition`. Les contrôles non créés par ce composant sont ignorés.
   *
   * Les définitions sans `type_widget` ne génèrent pas de contrôle : elles sont ignorées.
   */
  private removeObsoleteControls() {
    const definedNames = new Set(
      (this.formsDefinition || [])
        .filter((formDef) => formDef.type_widget)
        .map((f) => f.attribut_name)
    );
    for (const controlName of Array.from(this.ownedControls)) {
      if (!definedNames.has(controlName)) {
        this.myFormGroup.removeControl(controlName);
        this.ownedControls.delete(controlName);
      }
    }
  }

  /**
   * Ajoute le contrôle de `formDef` au `myFormGroup` et le référencie comme créé par ce composant.
   *
   * Avec `preserveControls`, si un contrôle du même nom a déjà été créé par ce composant il est
   * conservé (valeur incluse) : seuls ses validateurs et son état activé/désactivé sont mis à jour.
   * Un contrôle de même nom présent dans le `myFormGroup` mais créé par un autre acteur n'est
   * jamais remplacé ni référencé.
   *
   * @param formDef Définition du champ (`attribut_name`, `type_widget`, `required`, `disabled`, ...)
   */
  private addOrUpdateControl(formDef) {
    const name = formDef.attribut_name;
    const existing = this.myFormGroup.get(name);
    if (this.preserveControls && existing && this.ownedControls.has(name)) {
      this._dynformService.setControl(existing, formDef);
      return;
    }
    const alreadyInGroup = !!existing;
    this._dynformService.addNewControl(formDef, this.myFormGroup);
    if (!alreadyInGroup && this.myFormGroup.get(name)) {
      this.ownedControls.add(name);
    }
  }

  initDynamicForm() {
    if (this.autoGenerated) {
      if (!this.myFormGroup) {
        this.myFormGroup = this._dynformService.initFormGroup();
      }

      // HACK: formeSelect = formDefinition en mode autoGenerated = true
      // (on affiche tous les champs sans les filtrer au préalable)
      this.formsSelected = this.formsDefinition;
      this.formsDefinition.forEach((formDef) => {
        if (formDef.type_widget) {
          this.addOrUpdateControl(formDef);
        }
        // attribution de la valeur par defaut
        if (this.defaults && this.defaults[formDef.atribute_name] != null) {
          const value = {};
          value[formDef.atribute_name] = this.defaults[formDef.atribute_name];
          this.myFormGroup.patchValue(value);
        }
      });
    } else {
      // dans le cas non auto-généré
      // s'il y a des valeurs par defaut
      //   -on affiche les champs concernés
      //   - et on donne la valeur par défaut
      for (const [defaultKey, defaultValue] of Object.entries(this.defaults || {})) {
        const formDef = this.formsDefinition.find((formDef) => formDef.attribut_name == defaultKey);
        if (!formDef) {
          continue;
        }
        this.addFormControl(formDef);
        const value = {};
        value[defaultKey] = defaultValue;
        this.myFormGroup.patchValue(value);
      }

      this.selectControl.valueChanges
        .pipe(filter((value) => value !== null))
        .subscribe((formDef) => {
          this.addFormControl(formDef);
        });
      this.formsDefinition.sort((a, b) => {
        return a.attribut_label.localeCompare(b.attribut_label);
      });
    }
    this.setForms();
    this.formControlBuilded = true;
    this.myFormGroupChange.emit(this.myFormGroup);
  }

  /**
   * on teste s'il y a un changement entre this.myFormGroup.value et valueSaved;
   */
  hasValueChanged(newValue) {
    // Deep equals doesn't work with File type
    for (let key in newValue) {
      if (newValue[key] instanceof File) if (newValue[key] !== this.oldValue[key]) return true;
    }
    return !equal(newValue, this.oldValue);
  }

  setForms() {
    this.formsDisplayed = this.formsSelected.filter(
      (formDef) => !this._dynformService.getFormDefValue(formDef, 'hidden', this.myFormGroup.value)
    );
    this.formsHidden = this.formsSelected.filter((formDef) =>
      this._dynformService.getFormDefValue(formDef, 'hidden', this.myFormGroup.value)
    );
  }

  onFormsChange(newValue) {
    if (this.hasValueChanged(newValue)) {
      // mise à jour des formulaires affichés / cachés
      this.setForms();

      // pour dire aux formulaires qu'il y a un changement;

      // fy ExpressionChangedAfterItHasBeenCheckedError
      setTimeout(() => {
        this.update = true;
      });

      setTimeout(() => {
        this.update = false;
      }, 500);

      this.change.emit(newValue);
      this.oldValue = { ...newValue };
    }
  }

  /**
   * Retire un champ du formulaire (mode non auto-généré) : le champ redevient sélectionnable
   * et son contrôle est supprimé du `myFormGroup`.
   *
   * @param i Index du champ dans `formsSelected`
   */
  removeFormControl(i) {
    const formDef = this.formsSelected[i];
    this.formsSelected.splice(i, 1);
    this.formsDefinition.push(formDef);
    this.myFormGroup.removeControl(formDef.attribut_name);
    this.ownedControls.delete(formDef.attribut_name);
    this.selectControl.setValue(null);
  }

  /**
   * Ajoute un champ au formulaire (mode non auto-généré) : le champ n'est plus sélectionnable
   * et son contrôle est ajouté au `myFormGroup`.
   *
   * @param formDef Définition du champ à ajouter
   */
  addFormControl(formDef) {
    this.formsSelected.push(formDef);
    this.formsDefinition = this.formsDefinition.filter((form) => {
      return form.attribut_name !== formDef.attribut_name;
    });
    this.addOrUpdateControl(formDef);
    // pour être sûr que les composants (displayed et hidden) soient bien mis à jour)
    this.setForms();
  }
}
